'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict');
const key='ceh404.rebuilt.qa50.20261108';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 for(const [width,height] of [[390,844],[375,667],[1366,768]]){
  const page=await browser.newPage({viewport:{width,height}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/');
  await page.evaluate(key=>{
    const s=window.CEH_LOGIC.initial();
    localStorage.setItem(key,JSON.stringify({...s,scene:'S04',s04Mode:'edu',eduStep:1,eduPage:'documents',selected:['A'],name:'Тест'}));
  },key);
  await page.reload();
  const docs=page.locator('.edu-reference .edu-document-card--row');
  assert.equal(await docs.count(),2,'two original approved documents must be accessible');
  assert.equal(await page.locator('#edu-low').count(),0,'task must be a separate screen');
  await docs.first().click();
  const modal=page.locator('.edu-document-dialog');
  await modal.waitFor({state:'visible'});
  assert.ok(await modal.locator('img').evaluate(img=>img.naturalWidth>300),'scan failed to load');
  await modal.locator('[data-zoom-in]').click();
  assert.equal((await modal.locator('[data-zoom-level]').innerText()).trim(),'125%','zoom did not change');
  await modal.locator('.edu-document-dialog__close').click();
  assert.equal(await modal.isVisible(),false,'document should close');
  await page.locator('[data-act="eduGoTask"]').click();
  assert.equal(await page.locator('#edu-low').count(),1,'task missing after documents');
  await page.locator('#edu-low').fill('19,95');
  await page.locator('#edu-high').fill('20,05');
  await page.locator('[data-act="edu1"]').click();
  assert.equal(await page.locator('.edu-reference--result').count(),1,'result must be a new screen');
  const resultText=await page.locator('.edu-reference--result').innerText();
  assert.match(resultText,/19,95 мм/);
  assert.match(resultText,/20,05 мм/);
  assert.equal(await page.locator('#edu-low').count(),0,'form leaked into result');
  await page.locator('[data-act="eduContinue"]').click();
  assert.equal(await docs.count(),2,'after result, documents must be available');
  await page.locator('[data-act="eduGoTask"]').click();
  assert.match(await page.locator('.edu-task h3').innerText(),/Проверь результат контроля/);
  await page.locator('input[name="edu-part"][value="2"]').check();
  await page.locator('#edu-excess').fill('0,03');
  await page.locator('[data-act="edu2"]').click();
  assert.match(await page.locator('.edu-reference--result').innerText(),/0,03 мм/);
  await page.locator('[data-act="eduContinue"]').click();
  await page.locator('[data-act="eduGoTask"]').click();
  await page.locator('input[name="edu-conclusion"][value="2"]').check();
  await page.locator('[data-act="edu3"]').click();
  assert.equal(await page.locator('.edu-reference--result').count(),1);
  await page.locator('[data-act="eduContinue"]').click();
  await page.locator('[data-act="eduGoTask"]').click();
  for(const n of ['1','2','3','4'])await page.locator('input[name="edu-info"][value="'+n+'"]').check();
  await page.locator('[data-act="edu4"]').click();
  assert.match(await page.locator('.edu-reference--result').innerText(),/Проверка завершена/);
  await page.locator('[data-act="eduContinue"]').click();
  const state=await page.evaluate(()=>window.__CEH_TEST__.getState());
  assert.equal(state.s04Mode,'gromov','must return to original storyline after EDU-01');
  assert.deepEqual(errors,[],'runtime JavaScript errors');
  console.log('PASS EDU-01 reference sequence '+width+'x'+height);
  await page.close();
 }
 await browser.close();
})().catch(err=>{console.error(err);process.exit(1)});
